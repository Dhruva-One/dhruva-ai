"""Stub routes for every AI-service API derived from the functional spec (section 5 and AI capability flags).

The catalog lives in spec/endpoints.json and is generated by dhruva-platform/tools/spec-sync. Each stub
answers 501 with the requirement modules it serves. Implementing a route for real (same method and path)
retires its stub automatically, because stubs are only added for routes that do not exist yet.
"""

import json
from pathlib import Path

from fastapi import FastAPI
from fastapi.responses import JSONResponse

CATALOG = Path(__file__).resolve().parent.parent / "spec" / "endpoints.json"


def load_catalog() -> list[dict]:
    return json.loads(CATALOG.read_text(encoding="utf-8"))


def _stub(endpoint: dict):
    async def handler() -> JSONResponse:
        return JSONResponse(
            status_code=501,
            content={
                "statusCode": 501,
                "error": "Not Implemented",
                "message": f"Stub: {endpoint['why']}",
                "endpoint": f"{endpoint['m']} {endpoint['p']}",
                "requirements": endpoint["req"],
                "source": endpoint["src"],
            },
        )

    return handler


def register_spec_stubs(app: FastAPI) -> dict:
    existing = {(m, r.path) for r in app.routes for m in getattr(r, "methods", set()) or set()}
    endpoints = load_catalog()
    stubbed = 0
    for e in endpoints:
        if (e["m"], e["p"]) in existing:
            continue
        app.add_api_route(e["p"], _stub(e), methods=[e["m"]], include_in_schema=True,
                          summary=f"[stub] {e['why']}", tags=["spec stubs"])
        stubbed += 1
    return {"endpoints": len(endpoints), "stubbed": stubbed, "implemented": len(endpoints) - stubbed}
